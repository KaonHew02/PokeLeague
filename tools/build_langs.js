/* One dictionary file per language:
 *   node tools/build_langs.js             (tools/build.js runs it too)
 *   node tools/build_langs.js --missing   also lists what is not translated yet
 *   node tools/build_langs.js --missing --all   ... with every missing text
 *
 * Reads js/i18n/<lang>/*.js (one file per module, so parallel work never
 * edits the same file) and writes js/lang/<lang>.js with everything of that
 * language. locales.js downloads the player's one before the game starts.
 * English is the source language: it has no dictionary.
 *
 * Run it after editing any translation, also while developing with dev.html
 * (which loads the generated js/lang files).
 */
const fs = require('fs'), path = require('path'), vm = require('vm');
const ROOT = path.join(__dirname, '..');
const LANGS = ['es', 'fr', 'it', 'pt-BR', 'zh-Hans', 'zh-Hant'];

/** Dictionary source files, per language. */
function sources() {
  const out = [];
  for (const l of LANGS) {
    const dir = path.join(ROOT, 'js', 'i18n', l);
    if (!fs.existsSync(dir)) continue;
    for (const f of fs.readdirSync(dir).sort()) if (f.endsWith('.js')) out.push(`js/i18n/${l}/${f}`);
  }
  return out;
}

/** Runs dictionary files with a G.I18n.add that only records: -> [[dict, lang, context, file], ...] */
function capture(files = sources()) {
  const out = [];
  let file = '';
  const sb = { G: { I18n: { add: (d, l, c = '') => out.push([d, l, c, file]) } }, console };
  sb.window = sb;
  vm.createContext(sb);
  for (const f of files) { file = f; vm.runInContext(fs.readFileSync(path.join(ROOT, f), 'utf8'), sb, { filename: f }); }
  return out;
}

function build() {
  const all = capture();
  const bad = all.filter(([, l, , f]) => !LANGS.includes(l) || !f.startsWith(`js/i18n/${l}/`));
  if (bad.length) throw new Error('build_langs: dictionary with the wrong language: ' + bad.map(b => `${b[3]} says ${b[1]}`).join(', '));
  fs.mkdirSync(path.join(ROOT, 'js', 'lang'), { recursive: true });
  const sizes = [];
  for (const lang of LANGS) {
    // Everything without a context in one dictionary; one more per context.
    const plain = {}, ctx = {};
    for (const [d, l, c] of all) {
      if (l !== lang) continue;
      if (c) Object.assign(ctx[c] = ctx[c] || {}, d); else Object.assign(plain, d);
    }
    const items = [[plain, lang, '']].concat(Object.entries(ctx).map(([c, d]) => [d, lang, c]));
    const js = '/* GENERATED by tools/build_langs.js from js/i18n/' + lang + '/*.js: do not edit by hand. */\n'
      + '(window.PL_LANG_Q = window.PL_LANG_Q || []).push(' + items.map(i => JSON.stringify(i)).join(',\n') + ');\n';
    fs.writeFileSync(path.join(ROOT, 'js', 'lang', lang + '.js'), js);
    sizes.push(`${lang} ${(js.length / 1024).toFixed(0)} KB`);
  }
  return sizes;
}

module.exports = { build, capture, sources, LANGS };

if (require.main === module) {
  console.log('ok: dictionaries ' + build().join(' · '));
  if (process.argv.includes('--missing')) {
    const { keys } = require('./i18n_keys');
    const want = keys();
    const all = capture();
    for (const lang of LANGS) {
      const have = new Set();
      for (const [d, l, c] of all) if (l === lang && !c) Object.keys(d).forEach(k => have.add(k));
      const miss = [...want.keys()].filter(k => !have.has(k));
      console.log(`\n== ${lang}: ${miss.length} missing`);
      if (process.argv.includes('--all')) miss.forEach(k => console.log('  ' + JSON.stringify(k) + '   (' + want.get(k) + ')'));
    }
  }
}
