/* One dictionary file per language:
 *   node tools/build_langs.js             (tools/build.js runs it too)
 *   node tools/build_langs.js --missing   also lists what is not translated yet
 *   node tools/build_langs.js --missing --all   ... with every missing text
 *
 * Reads js/i18n/<lang>/*.js (one file per module, so parallel work never
 * edits the same file) and writes js/lang/<lang>.js with everything of that
 * language. locales.js downloads the player's one before the game starts.
 * English is the source language: it has no dictionary.
 *
 * Run it after editing any translation, also while developing with dev.html
 * (which loads the generated js/lang files).
 */
const fs = require('fs'), path = require('path'), vm = require('vm');
const ROOT = path.join(__dirname, '..');
const LANGS = ['es', 'fr', 'it', 'pt-BR', 'zh-Hans', 'zh-Hant'];

/** Dictionary source files, per language. */
function sources() {
  const out = [];
  for (const l of LANGS) {
    const dir = path.join(ROOT, 'js', 'i18n', l);
    if (!fs.existsSync(dir)) continue;
    for (const f of fs.readdirSync(dir).sort()) if (f.endsWith('.js')) out.push(`js/i18n/${l}/${f}`);
  }
  return out;
}

/** Runs dictionary files with a G.I18n.add that only records: -> [[dict, lang, context, file], ...] */
function capture(files = sources()) {
  const out = [];
  let file = '';
  const sb = { G: { I18n: { add: (d, l, c = '') => out.push([d, l, c, file]) } }, console };
  sb.window = sb;
  vm.createContext(sb);
  for (const f of files) { file = f; vm.runInContext(fs.readFileSync(path.join(ROOT, f), 'utf8'), sb, { filename: f }); }
  return out;
}

// ---------------- which region a text belongs to ----------------
const REGIONS = ['johto', 'hoenn', 'sinnoh'];
/** Generated data that holds no text of the game's own. */
const NO_TEXT = /^js\/data\/(names|species|encounters|dex-text|moves|sprites-meta|credits|music|items)\.js$/;

/** The game's source by part ('main': everything that is not a later region's content), with escapes undone. */
function partSources() {
  const out = { main: fs.readFileSync(path.join(ROOT, 'dev.html'), 'utf8') };
  const walk = dir => {
    for (const e of fs.readdirSync(path.join(ROOT, dir), { withFileTypes: true })) {
      const f = dir + '/' + e.name;
      if (e.isDirectory()) { if (!['js/lang', 'js/i18n', 'js/pack'].includes(f)) walk(f); continue; }
      if (!f.endsWith('.js') || f === 'js/app.min.js' || NO_TEXT.test(f)) continue;
      const part = REGIONS.find(r => f.startsWith(`js/content/${r}/`)) || 'main';
      out[part] = (out[part] || '') + '\n' + fs.readFileSync(path.join(ROOT, f), 'utf8').replace(/\\(['"`])/g, '$1').replace(/\\n/g, '\n');
    }
  };
  walk('js');
  return out;
}
/**
 * partOf(text): the part whose dictionary holds a text. A text that appears nowhere but in later regions' content goes with
 * the first of them (a pack brings those before it); one that also appears anywhere else, or nowhere as it is, stays in main.
 */
function partFinder() {
  const src = partSources(), N = 10;
  // Every run of ten characters of the main source: most texts of a region are ruled out at once.
  const runs = new Set();
  for (let i = 0; i + N <= src.main.length; i++) runs.add(src.main.substr(i, N));
  const known = new Map();
  return text => {
    if (known.has(text)) return known.get(text);
    let part = 'main';
    const inMain = text.length < N ? src.main.includes(text) : runs.has(text.substr(0, N)) && src.main.includes(text);
    if (!inMain) part = REGIONS.find(r => src[r].includes(text)) || 'main';
    known.set(text, part);
    return part;
  };
}

/** The Pokédex texts of one language (English where it has none): js/lang/<lang>/text.js. */
function texts() {
  const sb = { G: {} };
  for (const f of ['names', 'dex-text']) vm.runInNewContext(fs.readFileSync(path.join(ROOT, 'js', 'data', f + '.js'), 'utf8'), sb);
  const out = {};
  sb.G.NAMES.langs.forEach((lang, i) => {
    const o = {};
    for (const [kind, rows] of Object.entries(sb.G.DEX_TEXT)) {
      o[kind] = {};
      for (const [id, row] of Object.entries(rows)) o[kind][id] = row[i] || row[0] || '';
    }
    out[lang] = '/* GENERATED by tools/build_langs.js from js/data/dex-text.js: do not edit by hand. Data: PokeAPI (https://pokeapi.co/). */\n'
      + 'window.PL_TEXT = ' + JSON.stringify(o) + ';\n';
  });
  return out;
}

/** Writes js/lang/<lang>/: main.js, one file per later region, and text.js (the Pokédex texts; published pages only). */
function build() {
  const all = capture();
  const bad = all.filter(([, l, , f]) => !LANGS.includes(l) || !f.startsWith(`js/i18n/${l}/`));
  if (bad.length) throw new Error('build_langs: dictionary with the wrong language: ' + bad.map(b => `${b[3]} says ${b[1]}`).join(', '));
  const partOf = partFinder(), sizes = [];
  const dir = lang => { const d = path.join(ROOT, 'js', 'lang', lang); fs.mkdirSync(d, { recursive: true }); return d; };
  for (const [lang, js] of Object.entries(texts())) fs.writeFileSync(path.join(dir(lang), 'text.js'), js);
  for (const lang of LANGS) {
    // For each part, everything without a context in one dictionary; one more per context.
    const parts = {};
    for (const p of ['main', ...REGIONS]) parts[p] = { '': {} };
    for (const [d, l, c] of all) {
      if (l !== lang) continue;
      for (const [k, v] of Object.entries(d)) { const p = parts[partOf(k)]; (p[c] = p[c] || {})[k] = v; }
    }
    const kb = [];
    for (const [p, dicts] of Object.entries(parts)) {
      const items = Object.entries(dicts).map(([c, d]) => [d, lang, c]);
      const js = '/* GENERATED by tools/build_langs.js from js/i18n/' + lang + '/*.js: do not edit by hand. */\n'
        + '(window.PL_LANG_Q = window.PL_LANG_Q || []).push(' + items.map(i => JSON.stringify(i)).join(',\n') + ');\n';
      fs.writeFileSync(path.join(dir(lang), p + '.js'), js);
      kb.push((js.length / 1024).toFixed(0));
    }
    sizes.push(`${lang} ${kb.join('+')} KB`);
  }
  return sizes;
}

module.exports = { build, capture, sources, partFinder, partSources, texts, LANGS, REGIONS };

if (require.main === module) {
  console.log('ok: dictionaries ' + build().join(' · '));
  if (process.argv.includes('--missing')) {
    const { keys } = require('./i18n_keys');
    const want = keys();
    const all = capture();
    for (const lang of LANGS) {
      const have = new Set();
      for (const [d, l, c] of all) if (l === lang && !c) Object.keys(d).forEach(k => have.add(k));
      const miss = [...want.keys()].filter(k => !have.has(k));
      console.log(`\n== ${lang}: ${miss.length} missing`);
      if (process.argv.includes('--all')) miss.forEach(k => console.log('  ' + JSON.stringify(k) + '   (' + want.get(k) + ')'));
    }
  }
}
