/* The sprite artists of CREDITS.md as a script the game can load (file:// has no fetch):
 *   node tools/credits_js.js        writes js/data/credits.js (tools/build.js runs it too)
 * Run it after tools/fetch_credits.py rewrites CREDITS.md. tests/lint checks they agree.
 */
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');

/** Artist names from the table under "## Sprites", in its order. */
function artists(md = fs.readFileSync(path.join(ROOT, 'CREDITS.md'), 'utf8')) {
  const part = md.split(/^## /m).find(s => s.startsWith('Sprites')) || '';
  return part.split('\n').filter(l => /^\|/.test(l)).slice(2)
    .map(l => l.split('|')[1].trim()).filter(Boolean);
}

function write() {
  const out = '/* ============ GENERATED by tools/credits_js.js from CREDITS.md: do not edit by hand ============\n'
    + ' * The SpriteCollab artists whose Pokémon sprites the game uses (CC BY-NC 4.0), for the credits screen.\n */\n'
    + 'G.SPRITE_ARTISTS = ' + JSON.stringify(artists()) + ';\n';
  fs.writeFileSync(path.join(ROOT, 'js', 'data', 'credits.js'), out);
  return artists().length;
}

module.exports = { artists, write };
if (require.main === module) console.log('ok: ' + write() + ' artists in js/data/credits.js');
